function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved as Lang)) return saved as Lang;
  } catch {
    /* ok */
  }
  const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
  if (SUPPORTED.includes(nav as Lang)) return nav as Lang;
  return "en";
}

let _lang: Lang = detectLang();
document.documentElement.lang = _lang;

export function getLang(): Lang {
  return _lang;
}

export function setLang(lang: Lang): void {
  if (!SUPPORTED.includes(lang)) return;
  _lang = lang;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ok */
  }
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  let s = STR[_lang]?.[key] ?? STR.en[key] ?? STR.it[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function applyStatic(): void {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = (el as HTMLElement).dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = (el as HTMLElement).dataset.i18nTitle;
    if (key) el.setAttribute("title", t(key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = (el as HTMLElement).dataset.i18nAria;
    if (key) el.setAttribute("aria-label", t(key));
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", t("meta.description"));
  const titleKey = document.querySelector("title[data-i18n]")?.getAttribute("data-i18n");
  if (titleKey) document.title = t(titleKey);
}

export function onLangChange(cb: () => void): void {
  window.addEventListener("ot:langchange", cb);
}

export function emitLangChange(): void {
  applyStatic();
  window.dispatchEvent(new Event("ot:langchange"));
}

